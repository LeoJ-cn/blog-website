/**
 * 随机破坏指定数量的图片 URL
 *
 * @param {Array} sourceList 原始图片数组
 * @param {number} errorCount 需要制造多少条错误，默认 5
 * @returns {Array} 新数组，不修改原数组
 */
function injectRandomImageErrors(sourceList, errorCount = 5) {
  // 深拷贝，避免污染原始 mock 数据
  const list = structuredClone(sourceList)

  // 防止 errorCount 超过数组长度
  const count = Math.min(errorCount, list.length)

  // 记录已经选中过的下标，保证不会重复
  const selectedIndexes = new Set()

  while (selectedIndexes.size < count) {
    const index = Math.floor(Math.random() * list.length)
    selectedIndexes.add(index)
  }

  selectedIndexes.forEach((index) => {
    const item = list[index]

    // 50% 破坏缩略图
    // 50% 破坏原图
    const breakThumb = Math.random() < 0.5

    if (breakThumb) {
      const errorUrl = `http://test-error/error-${index}.jpg`

      item.thumbSrc = errorUrl

      // 如果 src 就是用于展示缩略图，也一起破坏
      item.src = errorUrl

      // 如果 model.path 原本使用缩略图，也同步修改
      if (item.model?.path === sourceList[index].thumbSrc) {
        item.model.path = errorUrl
      }
    } else {
      const errorUrl = `http://test-error/origin-${index}.jpg`

      item.originSrc = errorUrl

      // 如果 model.path 原本使用原图，也同步修改
      if (item.model?.path === sourceList[index].originSrc) {
        item.model.path = errorUrl
      }
    }
  })

  console.log(
    '随机破坏的图片位置：',
    [...selectedIndexes].map((index) => index + 1),
  )

  return list
}

